#!/usr/bin/env python3
"""Writes src/gonzales/app/kernel_list.mojo: compile_kernels(ctx) compiles every kernel instantiation the sources launch
with enqueue_function[...], so a run compiles them before the scene reaches the card (and a build can warm the driver's
cache with `gonzales --compile-kernels`). Run from the repository root; the Makefile runs it before each build."""
import os, re, sys

SRC = "src"
OUT = os.path.join(SRC, "gonzales", "app", "kernel_list.mojo")
LAUNCH = re.compile(r"enqueue_function(?:_checked|_experimental)?\[([A-Za-z_0-9]+)(\[[^\]]*\])?")
LITERAL = re.compile(r"\[\s*(True|False|-?\d+)(\s*,\s*(True|False|-?\d+))*\s*\]$")
# Launches whose parameters are the enclosing function's: the instantiations its callers make.
# Kernels too costly to precompile; they still compile lazily when launched.
SKIP: set[str] = set()
EXPAND = {"traverse_paths_gpu[rare_on, alpha_on]":
          ["[True, True]", "[True, False]", "[False, True]", "[False, False]"]}


def module_of(path):
    return os.path.splitext(os.path.relpath(path, SRC))[0].replace(os.sep, ".")


def imports(text):
    """name -> module for `from gonzales... import a, b` and parenthesized forms."""
    out = {}
    for m in re.finditer(r"^from\s+(gonzales[\w.]*)\s+import\s+(\([^)]*\)|[^\n]*)", text, re.M):
        for part in m.group(2).strip("()").replace("\n", " ").split(","):
            part = part.split("#")[0].strip()
            if part:
                bits = part.split(" as ")
                out[bits[-1].strip()] = (m.group(1), bits[0].strip())
    return out


def main():
    kernels = {}   # (module, name, params) -> True
    bad = []
    for root, _, files in os.walk(os.path.join(SRC, "gonzales")):
        for f in sorted(files):
            if not f.endswith(".mojo") or f == "kernel_list.mojo":
                continue
            path = os.path.join(root, f)
            text = open(path).read()
            imp = imports(text)
            for m in LAUNCH.finditer(text):
                name, params = m.group(1), m.group(2) or ""
                if name in imp:
                    mod, real = imp[name]
                elif re.search(r"^def\s+" + name + r"\b", text, re.M):
                    mod, real = module_of(path), name
                else:
                    bad.append(f"{path}: {name}")
                    continue
                key = name + params
                for v in EXPAND.get(key, [params]):
                    if v and not LITERAL.match(v):
                        bad.append(f"{path}: {key} (symbolic parameters)")
                        continue
                    if real not in SKIP:
                        kernels[(mod, real, v)] = True
    if bad:
        sys.exit("gen_kernel_list: unresolved launches:\n  " + "\n  ".join(sorted(set(bad))))
    names = sorted({(mod, real) for mod, real, _ in kernels})
    lines = ['"""Generated by Tools/gen_kernel_list.py from the enqueue_function launches; do not edit."""',
             "from std.time import perf_counter_ns", "from max.gpu.host import DeviceContext"]
    for mod, real in names:
        lines.append(f"from {mod} import {real} as _k_{mod.replace('.', '_')}_{real}")
    lines += ["", "", "def compile_kernels(ctx: DeviceContext, verbose: Bool = False, part: Int = 0, parts: Int = 1) -> Int:",
              '    """Compiles every launched kernel with index % parts == part; the number that failed."""',
              "    var failed = 0", "    var t = perf_counter_ns()"]
    for i, (mod, real, v) in enumerate(sorted(kernels)):
        lines += [f"    if {i} % parts == part:",
                  f'        if verbose: print("kernel {i}: {mod}.{real}{v}", end="", flush=True)',
                  "        t = perf_counter_ns()", "        try:",
                  f"            _ = ctx.compile_function[_k_{mod.replace('.', '_')}_{real}{v}]()", "        except:",
                  "            failed += 1",
                  "        if verbose: print(\"\", Float64(perf_counter_ns() - t) / 1.0e9, \"s\", flush=True)"]
    lines += ["    return failed", ""]
    text = "\n".join(lines)
    if not os.path.exists(OUT) or open(OUT).read() != text:
        open(OUT, "w").write(text)
    print(f"gen_kernel_list: {len(kernels)} kernel instantiations")


main()
